package com.nixbug.entebus.data.remote.operator.api

import com.nixbug.entebus.data.remote.operator.model.token.GrantType
import com.nixbug.entebus.data.remote.operator.model.token.OperatorTokenSchema
import com.nixbug.entebus.data.remote.operator.model.token.PlatformType
import retrofit2.Response
import retrofit2.http.Field
import retrofit2.http.FormUrlEncoded
import retrofit2.http.POST

interface OperatorTokenApi {
    /**
     * POST company/account/token
     * Create Token
     * **Issue a new access token for an operator after validating credentials.**                  - Verify the username and password.                  - Ensure the operator account is in &#x60;active status&#x60; before allowing token creation.                     - Maintain a limit of &#x60;5&#x60; active tokens per operator to control token rotation.                            - Generate a new Operator Token with a pair of access and refresh tokens.                      - The &#x60;expires_in&#x60; indicates the number of seconds until the access token expires, the maximum allowed access token validity is &#x60;60&#x60; minutes.                - The &#x60;refresh_before&#x60; indicates the datetime when the refresh token expires, the maximum allowed refresh token validity is &#x60;7&#x60; days.                - A new access token can be generated by using the refresh token before it expires.
     * Responses:
     *  - 200: Successful Response
     *  - 412: Precondition Failed
     *  - 401: Unauthorized
     *  - 404: Not Found
     *  - 406: Not Acceptable
     *  - 422: Validation Error
     *
     * @param companyId
     * @param username
     * @param password
     * @param platformType OTHER: 1, WEB: 2, NATIVE: 3, SERVER: 4 (optional)
     * @param clientDetails  (optional)
     * @param grantType  (optional)
     * @param scope  (optional, default to "")
     * @param clientId  (optional)
     * @param clientSecret  (optional)
     * @return [com.nixbug.entebus.data.remote.operator.model.token.OperatorTokenSchema]
     */
    @FormUrlEncoded
    @POST("company/account/token")
    suspend fun createTokenCompanyAccountTokenPost(
        @Field("company_id") companyId: Int,
        @Field("username") username: String,
        @Field("password") password: String,
        @Field("platform_type") platformType: PlatformType? = null,
        @Field("client_details") clientDetails: String? = null,
        @Field("grant_type") grantType: String? = null,
        @Field("scope") scope: String? = "",
        @Field("client_id") clientId: String? = null,
        @Field("client_secret") clientSecret: String? = null
    ): Response<OperatorTokenSchema>

    /**
     * POST company/account/token/refresh
     * Refresh Token
     * **Refresh an operator&#39;s access token using a valid refresh token.**                     - Verify the provided refresh token exists in the database.                  - Invalidate the current refresh token.                          - Generate a new &#x60;Operator Token&#x60; with a pair of access and refresh tokens.                     - The &#x60;expires_in&#x60; indicates the number of seconds until the access token expires, the maximum allowed access token validity is &#x60;60&#x60; minutes.                - The &#x60;refresh_before&#x60; indicates the datetime when the refresh token expires, the maximum allowed refresh token validity is &#x60;7&#x60; days.               - A new access token can be generated by using the refresh token before it expires.
     * Responses:
     *  - 200: Successful Response
     *  - 401: Unauthorized
     *  - 404: Not Found
     *  - 406: Not Acceptable
     *  - 422: Validation Error
     *
     * @param refreshToken
     * @param grantType PASSWORD: password, REFRESH_TOKEN: refresh_token (optional)
     * @return [OperatorTokenSchema]
     */
    @FormUrlEncoded
    @POST("company/account/token/refresh")
    suspend fun refreshTokenCompanyAccountTokenRefreshPost(
        @Field("refresh_token") refreshToken: String,
        @Field("grant_type") grantType: GrantType? = null
    ): Response<OperatorTokenSchema>

    /**
     * POST company/account/token/revoke
     * Revoke Token
     * **Revokes an access token or refresh token associated with the operator.**                  - Operator must have a valid access token.                  - Revokes the token (access or refresh) specified in the request body.                   - If the token is invalid, doesn&#39;t belong to the operator, or is already revoked, the operation is silently ignored.
     * Responses:
     *  - 200: Successful Response
     *  - 401: Unauthorized
     *  - 422: Validation Error
     *
     * @param token Access or refresh token
     * @return [Any]
     */
    @FormUrlEncoded
    @POST("company/account/token/revoke")
    suspend fun revokeTokenCompanyAccountTokenRevokePost(@Field("token") token: String): Response<Any>

}
